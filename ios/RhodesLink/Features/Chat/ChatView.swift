    /// 输入框占位：「对{当前对话的代理人名字}说些什么…」（参考敲敲聊天页文案）。
    private var inputPlaceholder: String {
        let name = model.title
        let bare = (name.hasPrefix("「") && name.hasSuffix("」") && name.count > 2)
            ? String(name.dropFirst().dropLast())
            : name
        return "对\(bare)说些什么…"
    }

